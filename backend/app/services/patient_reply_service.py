# Normalize a BCP-47 / long tag ("hi-IN") down to the template key ("hi").
def _normalize_language(language: str) -> str:
    if not language:
        return "en"
    code = language.strip().split("-")[0].lower()
    return code if code in _REPLY_TEMPLATES else "en"


def build_patient_reply(clinical: dict[str, Any], triage: dict[str, Any], language: str) -> str:
    """Compose a short, patient-friendly spoken reply in the patient's language."""

    templates = _REPLY_TEMPLATES[_normalize_language(language)]
    level = str(triage.get("triage_level", "GREEN")).upper()
    if level not in ("GREEN", "YELLOW", "RED"):
        level = "GREEN"
    return f"{templates['ack']} {templates[level.lower()]}"


def supported_reply_language(language: str) -> str:
    """Return the canonical language code actually used for the reply."""

    return _normalize_language(language)
